#!/usr/bin/env python3
"""Write ui/omarchy/mothership/KeyLayout.js from mothership/layout.py, so the Omarchy front end
draws the real keyboard. Run it again whenever layout.py changes:

    python3 ui/omarchy/gen_layout.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)

from mothership import layout  # noqa: E402

# Key cap legends by Linux key code (US layout). Codes not listed keep an empty cap.
LEGENDS = {
    1: "Esc", 59: "F1", 60: "F2", 61: "F3", 62: "F4", 63: "F5", 64: "F6", 65: "F7", 66: "F8",
    67: "F9", 68: "F10", 87: "F11", 88: "F12", 102: "Home", 107: "End", 111: "Del",
    41: "`", 2: "1", 3: "2", 4: "3", 5: "4", 6: "5", 7: "6", 8: "7", 9: "8", 10: "9", 11: "0",
    12: "-", 13: "=", 14: "Back", 248: "Mic",
    15: "Tab", 16: "Q", 17: "W", 18: "E", 19: "R", 20: "T", 21: "Y", 22: "U", 23: "I", 24: "O",
    25: "P", 26: "[", 27: "]", 43: "\\", 113: "Mute",
    58: "Caps", 30: "A", 31: "S", 32: "D", 33: "F", 34: "G", 35: "H", 36: "J", 37: "K", 38: "L",
    39: ";", 40: "'", 28: "Enter", 115: "Vol+",
    42: "Shift", 44: "Z", 45: "X", 46: "C", 47: "V", 48: "B", 49: "N", 50: "M", 51: ",", 52: ".",
    53: "/", 54: "Shift", 103: "↑", 114: "Vol-",
    29: "Ctrl", 125: "Super", 56: "Alt", 57: "", 100: "Alt", 127: "Menu", 97: "Ctrl",
    105: "←", 108: "↓", 106: "→",
}
EXTRA = {101: "Fn"}  # keys the kernel never reports


def build():
    by_led = {}
    for code, led in layout.KEYCODES.items():
        if code in LEGENDS and led not in by_led:
            by_led[led] = LEGENDS[code]
    by_led.update(EXTRA)
    keys, seen = [], set()
    for led in sorted(layout.KEYS, key=lambda k: (layout.KEYS[k][0], layout.KEYS[k][1], k)):
        row, x, w = layout.KEYS[led]
        if (row, x, w) in seen:   # 106 and 107 both light the Space bar: draw it once
            continue
        seen.add((row, x, w))
        alias = [o for o, g in layout.KEYS.items() if g == (row, x, w) and o != led]
        keys.append({"led": led, "row": row, "x": x, "w": w, "label": by_led.get(led, ""), "also": alias})
    return keys


def main():
    keys = build()
    out = os.path.join(HERE, "mothership", "KeyLayout.js")
    lines = [
        ".pragma library",
        "// Generated by ui/omarchy/gen_layout.py from mothership/layout.py. Do not edit by hand.",
        "// Each key: LED id, row (0 = Esc/F-keys .. 5 = Ctrl/Space), x and width on a canvas",
        "// `width` units wide; `also` lists other LEDs that light the same cap.",
        f"var width = {layout.WIDTH}",
        f"var rows = {layout.ROWS}",
        "var keys = [",
    ]
    lines += [" " + json.dumps(k, ensure_ascii=False) + "," for k in keys]
    lines.append("]")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(keys)} keys)")


if __name__ == "__main__":
    main()
